package ru.vkusdetstva.util

import kotlin.math.abs

/**
 * Готовые эмоциональные «рамки» для блюд — короткие тезисы, которые ставятся
 * вокруг рецепта, когда своей истории ещё нет или писать не хочется.
 * Формулировки подобраны так, чтобы не зависеть от рода и числа названия
 * блюда: название всегда стоит в кавычках и согласуется как приложение.
 *
 * Подпись добавляется отдельной строкой — например: «Любимая внучка Настя».
 */
object MemoryQuotes {

    /** Все рамки; {dish} заменяется названием блюда в кавычках. */
    val templates: List<String> = listOf(
        "«{dish}» — вкус, который я никогда не забуду.",
        "«{dish}» пахнет моим детством.",
        "Пока живёт вкус «{dish}» — жива память нашей семьи.",
        "Где бы мы ни были, вкус «{dish}» всегда возвращает нас домой.",
        "«{dish}» — наша семейная классика, проверенная поколениями.",
        "Самое тёплое воспоминание детства — это «{dish}».",
        "«{dish}» — блюдо, ради которого мы до сих пор собираемся за одним столом.",
        "Ни один праздник в нашем доме не обходился без «{dish}».",
        "«{dish}» — рецепт, который передаётся в нашей семье из рук в руки.",
        "Вкус «{dish}» — это короткое путешествие в детство.",
        "«{dish}» — то, что связывает все наши поколения за одним столом.",
        "«{dish}» — доказательство, что счастье бывает съедобным.",
        "Как бы ни менялась жизнь, «{dish}» остаётся нашим семейным якорем.",
        "«{dish}» — маленький праздник, который всегда с нами.",
        "Запах «{dish}» до сих пор собирает всю нашу семью на кухне.",
        "«{dish}» — вкус моего детства и гордость нашей семьи.",
        "«{dish}» — блюдо, которое старше меня и переживёт нас всех.",
        "В нашей семье говорят: если есть «{dish}» — значит, всё хорошо.",
        "«{dish}» — это любовь, которую подают горячей.",
        "Прошли годы, а вкус «{dish}» — как будто вчера.",
        "«{dish}» — страница нашей семейной книги, которую перечитываем чаще всего.",
        "Дети спрашивают про «{dish}» — значит, традиция продолжается.",
        "«{dish}» — вкус, с которого начинается каждое наше большое событие.",
        "Нет ничего роднее запаха «{dish}» из воскресной духовки.",
        "«{dish}» — наша память в съедобном виде.",
        "Каждый раз, когда я ем «{dish}», я снова ребёнок за бабушкиным столом.",
        "«{dish}» — то самое блюдо, которое просили записать все гости.",
        "Время за столом летит незаметно, когда появляется «{dish}».",
        "«{dish}» — семейная тайна, которой мы делимся только с самыми близкими.",
        "Однажды попробовав «{dish}», ты становишься частью нашей семьи."
    )

    private fun filled(template: String, dish: String): String =
        template.replace("{dish}", dish.trim().ifBlank { "Это блюдо" })

    /**
     * Готовая рамка: цитата + подпись отдельной строкой (если подпись задана).
     * Выбор цитаты детерминирован — один и тот же рецепт всегда получает одну
     * и ту же рамку, поэтому книга при пересборке не «мигает».
     */
    fun frame(dish: String, signature: String = "", seed: Int = 0): String {
        val quote = filled(templates[abs(seed) % templates.size], dish)
        return if (signature.isBlank()) quote else "$quote\n\n— $signature"
    }

    /** Подсказки для редактора: несколько разных рамок на выбор. */
    fun suggestions(dish: String, count: Int = 4, seed: Int = 0): List<String> {
        val size = templates.size
        return (0 until count).map { offset -> filled(templates[(seed + offset * 7) % size], dish) }
    }

    /** Стабильный seed для рецепта — рамка не меняется от пересборки книги. */
    fun seedFor(recipeId: Long, title: String): Int =
        abs((recipeId * 31 + title.hashCode() * 17).toInt())
}
